def render_printable(folder: str, title: str, lead: str, steps: list[str], groups: list[list[str]]) -> str:
    step_html = "\n".join(f'<p class="step">{step}</p>' for step in steps)
    cuts = "\n".join(
        f'<div class="cut">剪下这一组（第 {index + 1} 组）</div>\n<div class="grid">'
        + "".join(f'<div class="card">{card}</div>' for card in group)
        + "</div>"
        for index, group in enumerate(groups)
    )
    return f"""<!doctype html>
<html lang="zh-CN"><head><meta charset="utf-8"><title>{title}</title>
<style>{PRINT_CSS}</style></head>
<body>
<h1>{title}</h1>
<p class="lead">{lead}</p>
{step_html}
{cuts}
<div class="cut">在这里画/写（不要另起一张纸）</div>
<div class="blank"></div>
<p class="foot">SMP-{folder} · 动觉版（V-SMP 四版之一）· 打印后剪开卡片即可动手 ·
答案不在这张纸上，提交后由系统按同一套编码方案判。</p>
</body></html>
"""



        "|---|---|---|---|---|",
        "| 原始 w | 0 | 1/3 | 2/3 | 1 |",
        "",
        "计分链：",
        "",
        "```",
        "单条得分 x_i = 10 × w_i            （反向句 w_i = 1 − w_raw）",
